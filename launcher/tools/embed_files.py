#!/usr/bin/env python3
"""Writes a C++ source that embeds files as byte arrays (the launcher's fonts).

usage: embed_files.py OUT.cpp SYMBOL=FILE [SYMBOL=FILE ...]

Each SYMBOL becomes `extern const unsigned char SYMBOL[]` and `extern const unsigned int
SYMBOL_size` in namespace launcher, so the Windows launcher stays a single self-contained .exe.
"""
import sys


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    out = ["// Generated by launcher/tools/embed_files.py; do not edit.", "namespace launcher {"]
    for spec in argv[2:]:
        sym, path = spec.split("=", 1)
        with open(path, "rb") as f:
            data = f.read()
        out.append(f"extern const unsigned char {sym}[] = {{")
        for i in range(0, len(data), 24):
            out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"extern const unsigned int {sym}_size = {len(data)};")
    out.append("} // namespace launcher")
    with open(argv[1], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
