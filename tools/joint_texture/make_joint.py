#!/usr/bin/env python3
"""Procedural hand-rolled joint texture that replaces the cigarette prop (guest texture hash
8f3dc7227bda2c45, 16x16 DXT1) by default (runtime/src/builtin_tex.c).

Original art: everything is drawn here from a fixed seed (420), so the output is deterministic.
The only values taken from the game are the 16 circumferential shading factors (orig_shade), so
the joint keeps the prop's lighting falloff; no game image data is read or written.

UV layout (same as the prop): V = along the length (rows 0-3 of the 16 the mouth end / filter,
4-14 paper, 15 the lit end), U = around the circumference.

Usage:
  make_joint.py OUT_DIR [--size N]   writes OUT_DIR/8f3dc7227bda2c45.png (RGBA, N x N, default 64)
  make_joint.py --header PATH        writes the C header with the 64x64 texels (builtin_joint.h)
  make_joint.py --check PATH         exits 1 when PATH differs from a freshly generated header
Needs numpy and Pillow (e.g. `uv run --no-project --with numpy --with pillow python make_joint.py`).
"""
import os
import sys

import numpy as np
from PIL import Image

HASH = "8f3dc7227bda2c45"
HEADER_SIZE = 64


def make_joint(N=64):
    """N x N x 3 uint8 RGB image."""
    rng = np.random.default_rng(420)
    v = (np.arange(N) + 0.5) / N            # along the length (0 mouth -> 1 lit end)
    u = (np.arange(N) + 0.5) / N            # around the circumference
    V, U = np.meshgrid(v, u, indexing='ij')

    def smooth_noise(shape, scale):
        g = rng.random((shape[0] // scale + 2, shape[1] // scale + 2))
        im = Image.fromarray((g * 255).astype(np.uint8)).resize((shape[1] + scale * 2, shape[0] + scale * 2), Image.BICUBIC)
        a = np.asarray(im).astype(float)[scale:scale + shape[0], scale:scale + shape[1]] / 255
        return a

    # base off-white rolling paper, slightly warm
    paper = np.array([238, 233, 216], float)
    img = np.ones((N, N, 3)) * paper
    # circumferential shading from the original (columns 13-15 darker): keep the same falloff
    orig_shade = np.array([.94, .94, .94, .97, .97, .97, 1, 1, 1, 1, 1, 1, .96, .85, .85, .81])
    shade_u = np.interp(u * 16 - 0.5, np.arange(16), orig_shade)
    # taper illusion: the mouth end gets a stronger falloff (reads narrower), the lit end a softer one
    taper = 1 - (1 - shade_u[None, :]) * (1.6 - 0.9 * V)
    img *= taper[..., None]
    # wrinkles: long creases along the length plus a few diagonal ones
    creases = smooth_noise((N, N), max(2, N // 16)) - 0.5
    streak = smooth_noise((max(4, N // 8), N), 2)
    streak = np.asarray(Image.fromarray((streak * 255).astype(np.uint8)).resize((N, N), Image.BICUBIC)).astype(float) / 255 - 0.5
    diag = np.sin((U * 3 + V * 5) * 2 * np.pi + smooth_noise((N, N), max(2, N // 8)) * 6) * 0.5
    wr = 0.06 * creases + 0.08 * streak + 0.03 * diag
    img *= (1 + wr)[..., None]
    # glue seam along the length (slightly translucent / darker, faint green-brown showing through)
    seam = np.exp(-((U - 0.62) / 0.02) ** 2)
    img = img * (1 - 0.10 * seam[..., None]) + np.array([150, 140, 95]) * 0.10 * seam[..., None]
    # faint herb speckles showing through the paper
    sp = (rng.random((N, N)) > 0.985) & (V > 0.2) & (V < 0.85)
    img[sp] = img[sp] * 0.80 + np.array([110, 115, 70]) * 0.20
    # mouth end (old filter band, v < 0.25): rolled crutch - cream card with a spiral line
    m = V < 0.25
    spiral = (np.sin((U * 2 + V * 10) * 2 * np.pi) > 0.9)
    crutch = np.array([226, 214, 186], float) * taper[..., None]
    img[m] = crutch[m]
    img[m & spiral] *= 0.86
    # twisted paper just before the lit end: diagonal twist folds, slightly darker / scorched
    t = (V > 0.80) & (V < 0.94)
    tw = 0.5 + 0.5 * np.sin((U * 3 - V * 9) * 2 * np.pi)
    scorch = np.clip((V - 0.86) / 0.08, 0, 1)
    twc = img * (0.62 + 0.38 * tw)[..., None]
    twc = twc * (1 - scorch[..., None] * 0.55) + np.array([90, 60, 35]) * scorch[..., None] * 0.55
    img[t] = twc[t]
    # lit end: gray ash with a glowing ember ring
    e = V >= 0.94
    ash = np.array([125, 128, 134], float) * (0.85 + 0.3 * rng.random((N, N)))[..., None]
    glow = np.array([255, 120, 30], float) * (0.75 + 0.25 * rng.random((N, N)))[..., None]
    ring = ((V > 0.94) & (V < 0.97))
    img[e] = ash[e]
    img[ring] = glow[ring]
    fl = e & (rng.random((N, N)) > 0.6)
    img[fl] = glow[fl] * 0.9
    img = np.clip(img, 0, 255).astype(np.uint8)
    return img


def header_text(img):
    """C header with the texels as uint32_t 0xAARRGGBB (B8G8R8A8, the runtime's texel format)."""
    h, w = img.shape[:2]
    px = img.astype(np.uint32)
    texels = (0xFF << 24) | (px[..., 0] << 16) | (px[..., 1] << 8) | px[..., 2]
    lines = [
        "/* Generated by tools/joint_texture/make_joint.py --header; do not edit. Original procedural",
        " * art (seed 420), not game data: the built-in replacement for the cigarette prop texture",
        f" * {HASH} (runtime/src/builtin_tex.c). Texels are 0xAARRGGBB, row-major, {w}x{h}. */",
        "#ifndef BUILTIN_JOINT_H",
        "#define BUILTIN_JOINT_H",
        "#include <stdint.h>",
        f"#define BUILTIN_JOINT_WIDTH {w}",
        f"#define BUILTIN_JOINT_HEIGHT {h}",
        f"static const uint32_t builtin_joint_texels[{w * h}] = {{",
    ]
    flat = texels.reshape(-1)
    for i in range(0, len(flat), 8):
        lines.append("    " + ", ".join(f"0x{int(t):08x}" for t in flat[i:i + 8]) + ",")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) == 3 and argv[1] in ("--header", "--check"):
        text = header_text(make_joint(HEADER_SIZE))
        if argv[1] == "--header":
            with open(argv[2], "w", newline="\n") as f:
                f.write(text)
            print("wrote", argv[2])
            return 0
        with open(argv[2], newline="") as f:
            same = f.read() == text
        print(argv[2], "is up to date" if same else "differs from the generator output")
        return 0 if same else 1
    if len(argv) < 2 or argv[1].startswith("-"):
        print(__doc__)
        return 2
    out = argv[1]
    N = int(argv[argv.index("--size") + 1]) if "--size" in argv else 64
    img = make_joint(N)
    os.makedirs(out, exist_ok=True)
    Image.fromarray(img, "RGB").convert("RGBA").save(os.path.join(out, HASH + ".png"))
    print("wrote", N, "x", N)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
