"""Generates src/ktable.c: Xbox kernel export names by ordinal plus calling
convention and argument size.

Sources (both read-only references, not game data):
  - names by ordinal: ghidra-xbe XbeLoader.java, array `kernelExports`
  - signatures: nxdk lib/xboxkrnl/xboxkrnl.h (github.com/XboxDev/nxdk)

Usage: python3 gen_ktable.py <XbeLoader.java> <xboxkrnl.h> > src/ktable.c
"""
import re
import sys

QWORD_TYPES = {"LARGE_INTEGER", "ULARGE_INTEGER", "LONGLONG", "ULONGLONG", "QWORD", "DWORD64", "ULONG64", "LONG64"}


def names_by_ordinal(java):
    body = re.search(r"kernelExports\s*=\s*\{(.*?)\};", java, re.S).group(1)
    return re.findall(r'"([^"]*)"', body)


def param_dwords(params):
    params = re.sub(r"/\*.*?\*/|//[^\n]*", "", params).strip()
    if not params or params == "VOID" or params == "void":
        return 0, False
    total, variadic = 0, False
    for p in params.split(","):
        p = p.strip()
        if p == "...":
            variadic = True
            continue
        words = [w for w in re.split(r"[\s]+", p) if w not in ("IN", "OUT", "OPTIONAL", "CONST", "const", "volatile")]
        typ = words[0] if words else ""
        is_ptr = "*" in p
        total += 2 if (typ in QWORD_TYPES and not is_ptr) else 1
    return total, variadic


def signatures(header):
    sigs = {}
    header = re.sub(r"__attribute__\s*\(\(\s*noreturn\s*\)\)|DECLSPEC_NORETURN", "", header)
    for m in re.finditer(r"XBAPI\s+([^;{]*?)\s+(NTAPI|FASTCALL|CDECL)\s+(\w+)\s*\((.*?)\)\s*;", header, re.S):
        dwords, variadic = param_dwords(m.group(4))
        conv = {"NTAPI": "CC_STDCALL", "FASTCALL": "CC_FASTCALL", "CDECL": "CC_CDECL"}[m.group(2)]
        sigs[m.group(3)] = (conv, dwords, m.group(1).strip())
    for m in re.finditer(r"XBAPI\s+([\w\s]+?)\s+\*?(\w+)\s*(\[[^\]]*\])?\s*;", header):
        if "(" not in m.group(0):
            sigs.setdefault(m.group(2), ("CC_DATA", 0, m.group(1).strip()))
    return sigs


def main():
    names = names_by_ordinal(open(sys.argv[1]).read())
    sigs = signatures(open(sys.argv[2]).read())
    print("/* Generated by tools/gen_ktable.py -- do not edit.")
    print(" * Names: ghidra-xbe XbeLoader.java; signatures: nxdk lib/xboxkrnl/xboxkrnl.h. */")
    print('#include "kernel.h"\n')
    print("const KExport kexports[KEXPORT_COUNT] = {")
    for ordinal, name in enumerate(names):
        conv, dwords, ret = sigs.get(name, ("CC_UNKNOWN", 0, ""))
        print(f'    [{ordinal}] = {{"{name}", {conv}, {dwords}}}, /* {ret} */')
    print("};")
    sys.stderr.write(f"{len(names)} names, {sum(1 for n in names if n in sigs)} with signatures\n")


if __name__ == "__main__":
    main()
